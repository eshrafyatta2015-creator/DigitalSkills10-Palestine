"""توليد ملفات تحليل الوحدات الأربع بصيغة Word وفق نموذج مديرية يطا."""
from docx import Document
from docx.shared import Pt, Cm, RGBColor
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.oxml.ns import qn, nsdecls
from docx.oxml import parse_xml
import os

OUTPUT_DIR = os.path.join(os.path.dirname(__file__), "..", "docs", "unit-analysis")


def set_rtl(paragraph):
    pPr = paragraph._p.get_or_add_pPr()
    bidi = parse_xml(f'<w:bidi {nsdecls("w")}/>')
    pPr.append(bidi)


def add_heading_ar(doc, text, size=14, bold=True, color=None):
    p = doc.add_paragraph()
    set_rtl(p)
    run = p.add_run(text)
    run.bold = bold
    run.font.size = Pt(size)
    run.font.name = "Traditional Arabic"
    run._element.rPr.rFonts.set(qn("w:eastAsia"), "Traditional Arabic")
    if color:
        run.font.color.rgb = RGBColor(*color)
    p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    return p


def add_para(doc, text, bold=False, size=11):
    p = doc.add_paragraph()
    set_rtl(p)
    run = p.add_run(text)
    run.bold = bold
    run.font.size = Pt(size)
    run.font.name = "Traditional Arabic"
    run._element.rPr.rFonts.set(qn("w:eastAsia"), "Traditional Arabic")
    p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    p.paragraph_format.space_after = Pt(4)
    return p


def add_bullets(doc, items, style="List Paragraph"):
    for item in items:
        p = doc.add_paragraph(style=style)
        set_rtl(p)
        run = p.add_run(f"• {item}")
        run.font.size = Pt(11)
        run.font.name = "Traditional Arabic"
        run._element.rPr.rFonts.set(qn("w:eastAsia"), "Traditional Arabic")
        p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
        p.paragraph_format.space_after = Pt(2)


def add_table(doc, rows, headers=None):
    cols = len(rows[0])
    table = doc.add_table(rows=1 + (1 if headers else 0) + len(rows), cols=cols)
    table.style = "Table Grid"
    r = 0
    if headers:
        for j, h in enumerate(headers):
            cell = table.cell(0, j)
            cell.text = ""
            p = cell.paragraphs[0]
            set_rtl(p)
            run = p.add_run(h)
            run.bold = True
            run.font.size = Pt(11)
            run.font.name = "Traditional Arabic"
            run._element.rPr.rFonts.set(qn("w:eastAsia"), "Traditional Arabic")
            shading = parse_xml(f'<w:shd {nsdecls("w")} w:fill="D9E2F3"/>')
            cell._tc.get_or_add_tcPr().append(shading)
        r = 1
    for i, row in enumerate(rows):
        for j, val in enumerate(row):
            cell = table.cell(r + i, j)
            cell.text = ""
            p = cell.paragraphs[0]
            set_rtl(p)
            run = p.add_run(str(val))
            run.font.size = Pt(10)
            run.font.name = "Traditional Arabic"
            run._element.rPr.rFonts.set(qn("w:eastAsia"), "Traditional Arabic")
            p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    return table


def add_section_title(doc, text):
    p = doc.add_paragraph()
    set_rtl(p)
    run = p.add_run(f"\n{'='*60}\n{text}\n{'='*60}")
    run.bold = True
    run.font.size = Pt(12)
    run.font.color.rgb = RGBColor(0x1F, 0x47, 0x88)
    run.font.name = "Traditional Arabic"
    run._element.rPr.rFonts.set(qn("w:eastAsia"), "Traditional Arabic")
    p.alignment = WD_ALIGN_PARAGRAPH.RIGHT


def build_analysis(unit_num, title, subtitle, pages, content):
    doc = Document()
    style = doc.styles["Normal"]
    style.font.name = "Traditional Arabic"
    style.font.size = Pt(11)
    style._element.rPr.rFonts.set(qn("w:eastAsia"), "Traditional Arabic")

    section = doc.sections[0]
    section.right_margin = Cm(2)
    section.left_margin = Cm(2)
    section.top_margin = Cm(1.5)
    section.bottom_margin = Cm(1.5)

    # Header table
    add_heading_ar(doc, f"الوحدة {unit_num}: {title}", size=18, color=(0x1F, 0x47, 0x88))
    add_para(doc, subtitle, size=12)

    info = [
        ["عنوان الوحدة", title],
        ["الصف", "العاشر الأساسي"],
        ["المجالات / المحور", subtitle],
        ["الكلمات الرئيسية", ", ".join(content["keywords"])],
        ["الإطار الزمني", content["timeframe"]],
        ["الصفحات في الكتاب", pages],
        ["اسم المعلم/ة", "......................"],
        ["المدرسة", "......................"],
        ["المديرية", "......................"],
        ["الفصل الدراسي", "......................"],
        ["العام الدراسي", "2026-2027"],
    ]
    add_table(doc, info, headers=["البند", "التفاصيل"])

    # Unit summary
    add_section_title(doc, "ملخص الوحدة")
    add_para(doc, content["summary"])

    # Desired outcomes
    add_section_title(doc, "النتائج المرجوة")
    add_bullets(doc, content["outcomes"])

    # Educational objectives
    add_section_title(doc, "الأهداف التعليمية: سوف يفهم الطلبة أن")
    add_bullets(doc, content["objectives"])

    # Essential questions
    add_section_title(doc, "الأسئلة الأساسية عند تدريس مفهوم التكنولوجيا")
    add_bullets(doc, content["essential_questions"])

    # Skills and knowledge
    add_section_title(doc, "المهارات والمعرفة التي سيحصل عليها الطالب من هذه الوحدة")
    add_table(doc, content["skills_knowledge"], headers=["المعرفة", "المهارات"])

    # Terms
    add_section_title(doc, "مصطلحات")
    add_para(doc, "، ".join(content["terms"]))

    # Work steps
    add_section_title(doc, "خطوات عمل")
    add_bullets(doc, content["steps"])

    # Assessment evidence
    add_section_title(doc, "أدلة التقييم")

    add_para(doc, "أ) المهمات الأدائية:", bold=True)
    add_bullets(doc, content["performance_tasks"])

    add_para(doc, "ب) تقييم المهمات الأدائية:", bold=True)
    add_para(doc, content["performance_assessment"])

    add_para(doc, "ج) أدلة تقييم أخرى:", bold=True)
    add_bullets(doc, content["other_evidence"])

    add_para(doc, "د) معايير تقييم عمل الطالب:", bold=True)
    add_bullets(doc, content["criteria"])

    # Learning plan
    add_section_title(doc, "خطة التعلم")
    add_table(doc, content["learning_plan"], headers=["الحصة", "المحور", "المخرج التعليمي"])

    # Footer
    add_para(doc, "")
    add_para(doc, f"المصدر: الكتاب المدرسي المعتمد — المهارات الرقمية، الوحدة {unit_num} (ص {pages}).", size=9)
    add_para(doc, "نموذج تحليل تربوي وفق قالب مديرية يطا التربوية.", size=9)

    filepath = os.path.join(OUTPUT_DIR, f"unit{unit_num}-analysis.docx")
    doc.save(filepath)
    return filepath


